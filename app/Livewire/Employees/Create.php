<?php

namespace App\Livewire\Employees;

use App\Livewire\Employees\Concerns\ManagesEmployeeForm;
use App\Models\Employee;
use Illuminate\Database\UniqueConstraintViolationException;
use Illuminate\Support\Facades\Gate;
use Livewire\Component;

class Create extends Component
{
    use ManagesEmployeeForm;

    // Runs on every request to this component, so Front Desk cannot submit it either.
    public function boot(): void
    {
        Gate::authorize('admin');
    }

    public function save(): void
    {
        $data = $this->validatedEmployeeData();

        // employee_id is generated by the model. If two people save at the same
        // instant and collide on the unique index, try again with the next number.
        $employee = retry(
            3,
            fn () => Employee::create($data),
            0,
            fn ($e) => $e instanceof UniqueConstraintViolationException,
        );

        session()->flash('status', "{$employee->full_name} was added as {$employee->employee_id}.");

        $this->redirectRoute('employees.index', navigate: true);
    }

    public function render()
    {
        return view('livewire.employees.create');
    }
}